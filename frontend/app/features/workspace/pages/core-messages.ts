type CoreTranslator = <K extends CoreKey>(key: K, ...args: [Placeholders<(typeof corePageMessages.ja)[K]>] extends [never] ? [] : [params: Record<Placeholders<(typeof corePageMessages.ja)[K]>, string | number>]) => string;
export function useCoreI18n() {
  const i18n = useI18n();
  const c = ((key: CoreKey, params?: Record<string, string | number>) => {
    const template: string = corePageMessages[i18n.language][key];
    return template.replace(/\{([^{}]+)\}/g, (_, key: string) => { if (!params || !Object.hasOwn(params, key)) throw new Error(`Missing translation parameter: ${key}`); return typeof params[key] === "number" ? i18n.formatNumber(params[key]) : params[key]; });
  }) as CoreTranslator;
  return {
    ...i18n, c,
    vehicleName: (vehicle?: Vehicle) => vehicle?.model_name || i18n.t("common.notSet"),
    plateNumber: (vehicle?: Vehicle) => vehicle?.identifiers.find(identifier => identifier.kind === "plate_number" && !identifier.valid_to)?.value || i18n.t("common.notSet"),
  };
}
